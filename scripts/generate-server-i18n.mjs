/**
 * 国际化配置与服务端文案生成器。
 *
 * 输入是共享配置、服务端 catalog 和首屏 bootstrap 模板；无参数时同步生成 shared TypeScript、
 * Go/Worker 配置与 catalog、浏览器 bootstrap，`--check` 只验证生成物没有漂移。
 * 前端错误展示只共享稳定 code，不导入服务端翻译文本。
 */
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const rootDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const configPath = path.join(rootDir, "packages/shared/data/i18n-config.json");
const sourceDir = path.join(rootDir, "packages/shared/data/server-i18n");
const sharedConfigOutPath = path.join(rootDir, "packages/shared/src/i18n-config.ts");
const serverOutDir = path.join(rootDir, "apps/docker-server/cmd/renewlet/i18n");
const goConfigOutPath = path.join(rootDir, "apps/docker-server/cmd/renewlet/i18n_config_gen.go");
const workerOutPath = path.join(rootDir, "apps/worker/src/server-i18n-catalog.ts");
const clientBootstrapTemplatePath = path.join(rootDir, "apps/web/scripts/renewlet-client-bootstrap.template.js");
const clientBootstrapOutPath = path.join(rootDir, "apps/web/public/renewlet-client-bootstrap.js");
const checkMode = process.argv.includes("--check");

function readConfig() {
  const config = JSON.parse(fs.readFileSync(configPath, "utf8"));
  const locales = config.supportedLocales;
  if (!Array.isArray(locales) || locales.length === 0 || new Set(locales).size !== locales.length) {
    throw new Error("i18n config supportedLocales must be a non-empty unique array");
  }
  if (!locales.includes(config.sourceLocale) || !locales.includes(config.fallbackLocale)) {
    throw new Error("i18n config sourceLocale and fallbackLocale must be supported");
  }
  if (config.defaultPreference !== "auto") {
    throw new Error('i18n config defaultPreference must be "auto"');
  }
  return config;
}

function discoverCatalogLocales() {
  return fs.readdirSync(sourceDir)
    .map((name) => /^active\.(.+)\.json$/.exec(name)?.[1])
    .filter(Boolean)
    .sort();
}

function readCatalog(locale) {
  const filePath = path.join(sourceDir, `active.${locale}.json`);
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function placeholders(message) {
  const names = new Set();
  for (const match of message.matchAll(/\{([A-Za-z_][A-Za-z0-9_]*)\}/g)) {
    names.add(match[1]);
  }
  return [...names].sort();
}

function legacyPrintfPlaceholders(message) {
  return [...message.matchAll(/%(\d+\$)?[+#0\- ]*(\*|\d+)?(?:\.(\*|\d+))?[bcdeEfgGopqstTvxXU]/g)].map((match) => match[0]);
}

function stableStringify(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return JSON.stringify(value, null, 2);
  }
  const sorted = Object.fromEntries(Object.keys(value).sort().map((key) => [key, value[key]]));
  return `${JSON.stringify(sorted, null, 2)}\n`;
}

function renderClientBootstrap(config) {
  const template = fs.readFileSync(clientBootstrapTemplatePath, "utf8");
  const source = template
    .replace("__RENEWLET_SUPPORTED_LOCALES__", JSON.stringify(config.supportedLocales))
    .replace("__RENEWLET_FALLBACK_LOCALE__", JSON.stringify(config.fallbackLocale));
  if (source.includes("__RENEWLET_")) {
    throw new Error("client bootstrap template contains an unknown i18n placeholder");
  }
  return `// Code generated by scripts/generate-server-i18n.mjs; DO NOT EDIT.\n${source}`;
}

const config = readConfig();
const locales = config.supportedLocales;
const sourceLocale = config.sourceLocale;
const defaultLocale = config.fallbackLocale;
const catalogLocales = discoverCatalogLocales();
const catalogs = Object.fromEntries(locales.map((locale) => [locale, readCatalog(locale)]));
const sourceKeys = Object.keys(catalogs[sourceLocale]).sort();
const failures = [];

for (const locale of locales) {
  if (!catalogLocales.includes(locale)) failures.push(`missing server i18n catalog active.${locale}.json`);
}
for (const locale of catalogLocales) {
  if (!locales.includes(locale)) failures.push(`unsupported server i18n catalog active.${locale}.json`);
}

for (const locale of locales) {
  const catalog = catalogs[locale];
  const keys = Object.keys(catalog).sort();
  for (const key of sourceKeys) {
    if (!(key in catalog)) failures.push(`${locale} is missing key ${key}`);
  }
  for (const key of keys) {
    if (!sourceKeys.includes(key)) failures.push(`${locale} has extra key ${key}`);
    if (typeof catalog[key] !== "string" || catalog[key].trim() === "") {
      failures.push(`${locale} has empty server i18n message for ${key}`);
    }
    if (legacyPrintfPlaceholders(catalog[key] ?? "").length > 0) {
      failures.push(`${locale} uses legacy printf placeholder in ${key}; use named placeholders like {label}.`);
    }
  }
}

for (const key of sourceKeys) {
  const expected = placeholders(catalogs[sourceLocale][key]).join(",");
  for (const locale of locales.filter((locale) => locale !== sourceLocale)) {
    const actual = placeholders(catalogs[locale][key] ?? "").join(",");
    if (expected !== actual) {
      failures.push(`${locale} placeholder mismatch for ${key}: expected [${expected}], got [${actual}]`);
    }
  }
}

function goLocaleName(locale) {
  return `locale${locale.split(/[^A-Za-z0-9]+/).filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join("")}`;
}

function formatGoSource(source) {
  // Go 生成物先经 gofmt 再参与 --check，避免生成器与仓库格式化后的字节永远互相覆盖。
  const result = spawnSync("gofmt", { input: source, encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`gofmt failed for generated locale config: ${(result.stderr || result.error?.message || "unknown error").trim()}`);
  }
  return result.stdout;
}

const sharedConfigSource = [
  "// 由 scripts/generate-server-i18n.mjs 生成；源语言、运行时回退和账号偏好是三个独立契约。",
  `export const SUPPORTED_LOCALES = [${locales.map((locale) => JSON.stringify(locale)).join(", ")}] as const;`,
  "",
  "export type Locale = (typeof SUPPORTED_LOCALES)[number];",
  "",
  `export const SOURCE_LOCALE: Locale = ${JSON.stringify(sourceLocale)};`,
  `export const FALLBACK_LOCALE: Locale = ${JSON.stringify(defaultLocale)};`,
  `export const DEFAULT_LOCALE_PREFERENCE = ${JSON.stringify(config.defaultPreference)} as const;`,
  "export const LOCALE_PREFERENCES = [DEFAULT_LOCALE_PREFERENCE, ...SUPPORTED_LOCALES] as const;",
  "",
  "export type LocalePreference = (typeof LOCALE_PREFERENCES)[number];",
  "",
  "export function isLocale(value: unknown): value is Locale {",
  "  return typeof value === \"string\" && (SUPPORTED_LOCALES as readonly string[]).includes(value);",
  "}",
  "",
  "export function isLocalePreference(value: unknown): value is LocalePreference {",
  "  return value === DEFAULT_LOCALE_PREFERENCE || isLocale(value);",
  "}",
  "",
  "/** 无设备上下文时解析账号偏好；浏览器内的 auto 必须重新探测设备，不能调用此 helper。 */",
  "export function resolveLocalePreference(preference: LocalePreference): Locale {",
  "  return preference === DEFAULT_LOCALE_PREFERENCE ? FALLBACK_LOCALE : preference;",
  "}",
  "",
].join("\n");

const goLocaleConstants = locales.map((locale) => `\t${goLocaleName(locale)} appLocale = ${JSON.stringify(locale)}`);
const goPreferenceConstants = locales.map((locale) => `\tpreference${locale.split(/[^A-Za-z0-9]+/).filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join("")} appLocalePreference = ${JSON.stringify(locale)}`);
const goConfigSource = formatGoSource([
  "// Code generated by scripts/generate-server-i18n.mjs; DO NOT EDIT.",
  "",
  "package main",
  "",
  "type appLocalePreference string",
  "",
  "const (",
  ...goLocaleConstants,
  `\tsourceAppLocale appLocale = ${goLocaleName(sourceLocale)}`,
  `\tdefaultAppLocale appLocale = ${goLocaleName(defaultLocale)}`,
  `\tautoLocalePreference appLocalePreference = ${JSON.stringify(config.defaultPreference)}`,
  ...goPreferenceConstants,
  ")",
  "",
  `var supportedAppLocales = []appLocale{${locales.map(goLocaleName).join(", ")}}`,
  "",
].join("\n"));

const tsSource = [
  "// Code generated by scripts/generate-server-i18n.mjs; DO NOT EDIT.",
  "",
  `export const SERVER_I18N_LOCALES = ${JSON.stringify(locales, null, 2)} as const;`,
  "",
  "export type ServerI18nLocale = (typeof SERVER_I18N_LOCALES)[number];",
  "",
  `export const DEFAULT_SERVER_I18N_LOCALE: ServerI18nLocale = ${JSON.stringify(defaultLocale)};`,
  "",
  "export type ServerI18nCatalog = Record<string, string>;",
  "",
  `export const SERVER_I18N_CATALOGS = ${JSON.stringify(catalogs, null, 2)} as const satisfies Record<ServerI18nLocale, ServerI18nCatalog>;`,
  "",
  "export type ServerI18nKey = keyof (typeof SERVER_I18N_CATALOGS)[typeof DEFAULT_SERVER_I18N_LOCALE];",
  "",
].join("\n");

const outputs = [
  { path: sharedConfigOutPath, source: sharedConfigSource },
  { path: goConfigOutPath, source: goConfigSource },
  { path: clientBootstrapOutPath, source: renderClientBootstrap(config) },
  ...locales.map((locale) => ({
    path: path.join(serverOutDir, `active.${locale}.json`),
    source: stableStringify(catalogs[locale]),
  })),
  { path: workerOutPath, source: tsSource },
];

for (const output of outputs) {
  if (!fs.existsSync(output.path)) {
    if (checkMode) failures.push(`${path.relative(rootDir, output.path)} is missing. Run \`pnpm generate:server-i18n\`.`);
    continue;
  }
  if (checkMode && fs.readFileSync(output.path, "utf8") !== output.source) {
    failures.push(`${path.relative(rootDir, output.path)} is out of sync. Run \`pnpm generate:server-i18n\`.`);
  }
}

if (failures.length > 0) {
  console.error(failures.join("\n"));
  process.exit(1);
}

if (checkMode) {
  console.log(`server i18n catalogs OK (${sourceKeys.length} keys, ${locales.length} locales).`);
} else {
  for (const output of outputs) {
    fs.mkdirSync(path.dirname(output.path), { recursive: true });
    fs.writeFileSync(output.path, output.source);
  }
  console.log(`generated server i18n catalogs (${sourceKeys.length} keys, ${locales.length} locales).`);
}
